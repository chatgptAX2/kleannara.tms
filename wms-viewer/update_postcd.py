def normalize_gu(raw):
    """공백 제거 후 정규화"""
    return re.sub(r'\s+', ' ', raw.strip())

def parse_addr(addr):
    """
    ADDR01 문자열에서 (시도코드, 구군명) 추출
    반환: (sido, gu) or (None, None)
    """
    if not addr or not addr.strip():
        return None, None

    addr = addr.strip()

    # 시/도 추출
    sido = None
    for keyword, code in sorted(SIDO_MAP.items(), key=lambda x: -len(x[0])):
        if addr.startswith(keyword) or (keyword in addr and not sido):
            sido = code
            break

    # 구/군 추출 (긴 패턴 우선)
    for pat in GU_PATTERNS:
        m = re.search(pat, addr)
        if m:
            gu = normalize_gu(m.group())
            return sido, gu

    return sido, None

def get_new_postcd(addr):
    """
    ADDR01 → 신규 5자리 우편번호 (대표값: 시작 우편번호)
    """
    sido, gu = parse_addr(addr)
    if not gu:
        return None

    # 시/도 + 구 조합으로 범위 찾기
    key = (gu, sido) if sido else None

    # 1순위: 시/도 + 구 정확 매칭
    if key and key in REGION_RANGE:
        return REGION_RANGE[key][0]  # 시작값을 대표값으로

    # 2순위: 구명만으로 매칭 (시/도 없을 때)
    matches = [(k, v) for k, v in REGION_RANGE.items() if k[0] == gu]
    if len(matches) == 1:
        return matches[0][1][0]

    return None

def get_range(gu, sido):
    """(gu, sido) → (start, end) or (None, None)"""
    key = (gu, sido)
    if key in REGION_RANGE:
        return REGION_RANGE[key]
    # 구명만으로
    matches = [(k, v) for k, v in REGION_RANGE.items() if k[0] == gu]
    if len(matches) == 1:
        return matches[0][1]
    return None, None


