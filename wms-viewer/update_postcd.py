def run():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row

    # ── 작업1: BZPTN POSTCD 갱신 ─────────────────────────
    print("=" * 60)
    print("작업1: BZPTN 납품처 POSTCD 신규 우편번호 갱신")
    print("=" * 60)

    rows = conn.execute(
        "SELECT PTNRKY, ADDR01, POSTCD FROM BZPTN WHERE TRIM(ADDR01) != '' AND ADDR01 IS NOT NULL"
    ).fetchall()
    print(f"ADDR01 있는 납품처: {len(rows)}건")

    updated = 0
    skipped_no_match = 0
    skipped_already_new = 0

    update_list = []
    no_match_samples = []

    for r in rows:
        ptnrky = r['PTNRKY']
        addr   = r['ADDR01']
        old_pc = str(r['POSTCD'] or '').strip()

        new_pc = get_new_postcd(addr)

        if new_pc is None:
            skipped_no_match += 1
            if len(no_match_samples) < 10:
                no_match_samples.append((ptnrky, addr, old_pc))
            continue

        # 이미 신규 5자리인 경우 (하이픈 없는 5자리 숫자)
        if re.match(r'^\d{5}$', old_pc) and old_pc == new_pc:
            skipped_already_new += 1
            continue

        update_list.append((new_pc, ptnrky))
        updated += 1

    print(f"  → 갱신 대상: {updated}건")
    print(f"  → 주소 매핑 불가 (생략): {skipped_no_match}건")
    print(f"  → 이미 최신 (생략): {skipped_already_new}건")

    if no_match_samples:
        print("\n  [매핑 불가 샘플 (최대 10건)]")
        for s in no_match_samples:
            print(f"    PTNRKY={s[0]} ADDR01=[{s[1][:40]}] 기존POSTCD={s[2]}")

    # 실제 UPDATE 실행
    if update_list:
        conn.executemany("UPDATE BZPTN SET POSTCD=? WHERE PTNRKY=?", update_list)
        conn.commit()
        print(f"\n  ✅ BZPTN POSTCD {updated}건 갱신 완료")

        # 검증 샘플
        print("\n  [갱신 결과 샘플 10건]")
        sample_keys = [u[1] for u in update_list[:10]]
        for key in sample_keys:
            row = conn.execute(
                "SELECT PTNRKY, NAME01, ADDR01, POSTCD FROM BZPTN WHERE PTNRKY=?", (key,)
            ).fetchone()
            if row:
                print(f"    {row['PTNRKY']} | {str(row['NAME01'])[:10]} | {str(row['ADDR01'])[:30]} | → {row['POSTCD']}")
    else:
        print("  갱신할 데이터 없음")

    # ── 작업2: TMS_REGION USARG3/USARG4 우편번호 범위 갱신 ──
    print()
    print("=" * 60)
    print("작업2: TMS_REGION USARG3(시작)/USARG4(종료) 우편번호 범위 갱신")
    print("=" * 60)

    regions = conn.execute(
        "SELECT CMCDVL, CDESC1, CDESC2, USARG2, USARG3, USARG4 FROM CMCDV WHERE CMCDKY='TMS_REGION' ORDER BY CMCDVL"
    ).fetchall()
    print(f"TMS_REGION 건수: {len(regions)}건")

    region_updates = []
    region_no_match = []

    for r in regions:
        cmcdvl = r['CMCDVL']
        gu     = str(r['CDESC1'] or '').strip()
        sido   = str(r['CDESC2'] or '').strip()

        rng_start, rng_end = get_range(gu, sido)

        if rng_start is None:
            region_no_match.append((cmcdvl, gu, sido))
            continue

        region_updates.append((rng_start, rng_end, 'TMS_REGION', cmcdvl))

    print(f"  → 갱신 대상: {len(region_updates)}건")
    print(f"  → 매핑 불가: {len(region_no_match)}건")

    if region_no_match:
        print("\n  [TMS_REGION 매핑 불가]")
        for s in region_no_match:
            print(f"    CMCDVL={s[0]} CDESC1={s[1]} CDESC2={s[2]}")

    if region_updates:
        conn.executemany(
            "UPDATE CMCDV SET USARG3=?, USARG4=? WHERE CMCDKY=? AND CMCDVL=?",
            region_updates
        )
        conn.commit()
        print(f"\n  ✅ TMS_REGION USARG3/USARG4 {len(region_updates)}건 갱신 완료")

