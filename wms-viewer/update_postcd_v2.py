def parse_addr(addr1, addr2=''):
    """ADDR01 + ADDR02 결합 주소에서 (시도코드, 구군명) 추출"""
    addr = str(addr1 or '').strip() + ' ' + str(addr2 or '').strip()
    addr = addr.strip()
    if not addr:
        return None, None

    sido = None
    # 긴 시/도 키워드부터 매칭 (특별자치도 등 우선)
    for kw, code in sorted(SIDO_MAP.items(), key=lambda x: -len(x[0])):
        if kw in addr:
            sido = code
            break

    for pat in GU_PATTERNS:
        m = re.search(pat, addr)
        if m:
            gu = re.sub(r'\s+', '', m.group().strip())  # 공백 제거 후 정규화
            # REGION_RANGE 키와 비교 시 공백 포함 버전도 확인
            # 예: '수원시 장안구' 패턴이 '수원시장안구'로 매칭될 수 있음
            gu_spaced = re.sub(r'(?<=[시군도])(?=[가-힣])', ' ', gu)  # 복합명 공백 복원
            return sido, m.group().strip()

    return sido, None


def normalize_gu(raw_gu):
    """패턴 매칭 결과를 REGION_RANGE 키와 맞게 정규화"""
    if not raw_gu:
        return raw_gu
    # '수원시  장안구' → '수원시 장안구'
    return re.sub(r'\s+', ' ', raw_gu.strip())


def get_range(gu, sido):
    """(gu, sido) → (start5, end5) or (None, None)"""
    gu_norm = normalize_gu(gu)
    key = (gu_norm, sido)
    if key in REGION_RANGE:
        return REGION_RANGE[key]
    # 시/도 없을 때 유일 매칭
    if sido is None:
        matches = [(k, v) for k, v in REGION_RANGE.items() if k[0] == gu_norm]
        if len(matches) == 1:
            return matches[0][1]
    return None, None


def get_start(gu, sido):
    s, _ = get_range(gu, sido)
    return s


